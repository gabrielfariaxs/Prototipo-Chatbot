CREATE OR REPLACE FUNCTION "public"."buscar_processos"("query_embedding" "public"."vector", "match_threshold" double precision, "match_count" integer) RETURNS TABLE("id" bigint, "processo" "text", "setor" "text", "sistema" "text", "conteudo" "text", "similarity" double precision)
    LANGUAGE "plpgsql"
    AS $$
begin
  return query
  select
    documentos_arthromed.id,
    documentos_arthromed.processo,
    documentos_arthromed.setor,
    documentos_arthromed.sistema,
    documentos_arthromed.conteudo,
    1 - (documentos_arthromed.embedding <=> query_embedding) as similarity
  from documentos_arthromed
  where 1 - (documentos_arthromed.embedding <=> query_embedding) > match_threshold
  order by documentos_arthromed.embedding <=> query_embedding
  limit match_count;
end;
$$;


ALTER FUNCTION "public"."buscar_processos"("query_embedding" "public"."vector", "match_threshold" double precision, "match_count" integer) OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."buscar_processos"("query_embedding" "public"."vector", "match_threshold" double precision, "match_count" integer, "filter_setor" "text") RETURNS TABLE("id" bigint, "processo" "text", "setor" "text", "sistema" "text", "conteudo" "text", "similarity" double precision)
    LANGUAGE "plpgsql"
    AS $$
BEGIN
  RETURN QUERY
  SELECT
    documentos_arthromed.id,
    documentos_arthromed.processo,
    documentos_arthromed.setor,
    documentos_arthromed.sistema,
    documentos_arthromed.conteudo,
    1 - (documentos_arthromed.embedding <=> query_embedding) AS similarity
  FROM documentos_arthromed
  WHERE (1 - (documentos_arthromed.embedding <=> query_embedding) > match_threshold)
    AND (documentos_arthromed.setor ILIKE '%' || filter_setor || '%')
  ORDER BY documentos_arthromed.embedding <=> query_embedding
  LIMIT match_count;
END;
$$;


ALTER FUNCTION "public"."buscar_processos"("query_embedding" "public"."vector", "match_threshold" double precision, "match_count" integer, "filter_setor" "text") OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."match_documents"("query_embedding" "public"."vector", "match_threshold" double precision, "match_count" integer) RETURNS TABLE("id" bigint, "content" "text", "metadata" "jsonb", "similarity" double precision)
    LANGUAGE "sql" STABLE
    AS $$
  select
    id,
    content,
    metadata,
    1 - (documents.embedding <=> query_embedding) as similarity
  from documents
  where 1 - (documents.embedding <=> query_embedding) > match_threshold
  order by documents.embedding <=> query_embedding
  limit match_count;
$$;


